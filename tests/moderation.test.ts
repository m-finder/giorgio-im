import { describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { nextTick } from 'vue'
import ImWidget from '../src/ImWidget.vue'
import { createIM } from '../src'
import type { ImInit, ImWidgetApi } from '../src/types'

const init: ImInit = {
  user: { id: 'me', username: '我' },
  friend: [{ id: 0, groupname: '好友', list: [{ id: 'alice', username: 'Alice' }] }],
  group: [{ id: 'room', groupname: '讨论组', ownerId: 'me', members: 2 }],
}
const members = [{ id: init.user.id, username: init.user.username }, { id: 'alice', username: 'Alice' }]

it.each(['me', 'alice', undefined, 0])('shows owner badges and restricts management for owner %s', async ownerId => {
  const wrapper = mount(ImWidget, { props: {
    init: { ...init, user: { id: 0, username: '我' }, group: [{ ...init.group![0], ownerId }] },
    loadGroupMembers: () => [{ id: 0, username: '我' }, { id: 'me', username: '原群主' }, members[1]],
  } })
  ;(wrapper.vm as unknown as ImWidgetApi).chat({ id: 'room', type: 'group', groupname: '讨论组' })
  await nextTick()
  await wrapper.get('[aria-label="查看群成员"]').trigger('click')
  await flushPromises()
  expect(wrapper.findAll('.gim-owner-badge')).toHaveLength(ownerId === undefined ? 0 : 1)
  expect(wrapper.find('[aria-label="解散群聊"]').exists()).toBe(ownerId === 0)
  expect(wrapper.find('[aria-label="全员禁言"]').exists()).toBe(ownerId === 0)
  expect(wrapper.find('[aria-label="移出Alice"]').exists()).toBe(ownerId === 0)
  expect(wrapper.find('[aria-label="退出群聊"]').exists()).toBe(ownerId !== 0)
  expect(wrapper.find('[aria-label="移出我"]').exists()).toBe(false)
  wrapper.unmount()
})

describe('group owner management', () => {
  it('confirms removal and retains members until the host accepts', async () => {
    const removeGroupMember = vi.fn().mockResolvedValueOnce(false).mockResolvedValueOnce(true)
    const wrapper = mount(ImWidget, { props: { init, loadGroupMembers: () => members, removeGroupMember } })
    ;(wrapper.vm as unknown as ImWidgetApi).chat({ id: 'room', type: 'group', groupname: '讨论组' })
    await nextTick()
    await wrapper.get('[aria-label="查看群成员"]').trigger('click')
    await flushPromises()
    await wrapper.get('[aria-label="移出Alice"]').trigger('click')
    expect(removeGroupMember).not.toHaveBeenCalled()
    await wrapper.get('.gim-management-footer button:first-child').trigger('click')
    expect(wrapper.findAll('.gim-member-row')).toHaveLength(2)
    await wrapper.get('[aria-label="移出Alice"]').trigger('click')
    await wrapper.get('.gim-management-form').trigger('submit')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('失败')
    expect(wrapper.emitted('groupMemberRemoved')).toBeUndefined()
    await wrapper.get('.gim-management-form').trigger('submit')
    await flushPromises()
    expect(removeGroupMember).toHaveBeenLastCalledWith(expect.objectContaining({ id: 'room', ownerId: 'me' }), expect.objectContaining({ id: 'alice' }))
    expect(wrapper.findAll('.gim-member-row')).toHaveLength(1)
    expect(wrapper.get('[aria-label="查看群成员"]').text()).toContain('1')
    expect(wrapper.emitted('groupMemberRemoved')).toHaveLength(1)
    wrapper.unmount()
  })

  it('mutes and unmutes a member only after saving', async () => {
    const muteGroupMember = vi.fn().mockResolvedValueOnce(false).mockResolvedValue(true)
    const wrapper = mount(ImWidget, { props: { init, loadGroupMembers: () => members, muteGroupMember } })
    ;(wrapper.vm as unknown as ImWidgetApi).chat({ id: 'room', type: 'group', groupname: '讨论组' })
    await nextTick()
    await wrapper.get('[aria-label="查看群成员"]').trigger('click')
    await flushPromises()
    await wrapper.get('[aria-label="禁言Alice"]').trigger('click')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('失败')
    expect(wrapper.find('[aria-label="解除Alice禁言"]').exists()).toBe(false)
    await wrapper.get('[aria-label="禁言Alice"]').trigger('click')
    await flushPromises()
    expect(wrapper.get('[aria-label="解除Alice禁言"]').text()).toContain('解除禁言')
    expect(wrapper.get('.gim-muted-badge').text()).toBe('已禁言')
    await wrapper.get('[aria-label="解除Alice禁言"]').trigger('click')
    await flushPromises()
    expect(muteGroupMember).toHaveBeenLastCalledWith(expect.objectContaining({ id: 'room' }), expect.objectContaining({ id: 'alice' }), false)
    expect(wrapper.find('.gim-muted-badge').exists()).toBe(false)
    expect(wrapper.emitted('groupMemberMuted')).toHaveLength(2)
    wrapper.unmount()
  })

  it('toggles all-member muting while allowing the owner to speak', async () => {
    const muteGroup = vi.fn().mockResolvedValueOnce(false).mockResolvedValue(true)
    const wrapper = mount(ImWidget, { props: { init, loadGroupMembers: () => members, muteGroup } })
    ;(wrapper.vm as unknown as ImWidgetApi).chat({ id: 'room', type: 'group', groupname: '讨论组' })
    await nextTick()
    await wrapper.get('[aria-label="查看群成员"]').trigger('click')
    await flushPromises()
    await wrapper.get('[aria-label="全员禁言"]').trigger('click')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('失败')
    await wrapper.get('[aria-label="全员禁言"]').trigger('click')
    await flushPromises()
    expect(wrapper.find('[aria-label="解除全员禁言"]').exists()).toBe(true)
    await wrapper.get('[aria-label="关闭弹窗"]').trigger('click')
    await wrapper.get('[aria-label="输入消息"]').setValue('群公告')
    await wrapper.get('[aria-label="输入消息"]').trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendMessage')).toHaveLength(1)
    await wrapper.get('[aria-label="查看群成员"]').trigger('click')
    await wrapper.get('[aria-label="解除全员禁言"]').trigger('click')
    await flushPromises()
    expect(muteGroup).toHaveBeenLastCalledWith(expect.objectContaining({ id: 'room' }), false)
    expect(wrapper.emitted('groupMuted')).toHaveLength(2)
    wrapper.unmount()
  })

  it('confirms dissolution and removes the group only after success', async () => {
    const dismissGroup = vi.fn().mockResolvedValueOnce(false).mockResolvedValueOnce(true)
    const wrapper = mount(ImWidget, { props: { init, dismissGroup } })
    const api = wrapper.vm as unknown as ImWidgetApi
    api.open()
    api.chat({ id: 'room', type: 'group', groupname: '讨论组' })
    await nextTick()
    await wrapper.get('[aria-label="查看群成员"]').trigger('click')
    await wrapper.get('[aria-label="解散群聊"]').trigger('click')
    expect(dismissGroup).not.toHaveBeenCalled()
    await wrapper.get('.gim-management-form').trigger('submit')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('失败')
    expect(wrapper.find('.gim-chat').exists()).toBe(true)
    await wrapper.get('.gim-management-form').trigger('submit')
    await flushPromises()
    expect(wrapper.find('.gim-chat').exists()).toBe(false)
    api.getMessage({ id: 'room', type: 'group', content: '旧消息' })
    await wrapper.get('.gim-tabs button:nth-child(2)').trigger('click')
    expect(wrapper.findAll('.gim-contact')).toHaveLength(0)
    expect(wrapper.emitted('groupDismissed')).toHaveLength(1)
    expect(wrapper.emitted('groupLeft')).toBeUndefined()
    wrapper.unmount()
  })

  it('rechecks ownership when confirming a pending removal', async () => {
    const removeGroupMember = vi.fn()
    const wrapper = mount(ImWidget, { props: { init, loadGroupMembers: () => members, removeGroupMember } })
    ;(wrapper.vm as unknown as ImWidgetApi).chat({ id: 'room', type: 'group', groupname: '讨论组' })
    await nextTick()
    await wrapper.get('[aria-label="查看群成员"]').trigger('click')
    await flushPromises()
    await wrapper.get('[aria-label="移出Alice"]').trigger('click')
    await wrapper.setProps({ init: { ...init, group: [{ ...init.group![0], ownerId: 'alice' }] } })
    await wrapper.get('.gim-management-form').trigger('submit')
    await flushPromises()
    expect(removeGroupMember).not.toHaveBeenCalled()
    expect(wrapper.get('[role="alert"]').text()).toContain('群主')
    wrapper.unmount()
  })
})

it('applies server mute updates through createIM without affecting private chats', async () => {
  const target = document.createElement('div')
  const onSendMessage = vi.fn()
  const im = createIM({ init: { ...init, group: [{ ...init.group![0], ownerId: 'alice' }] }, target, onSendMessage })
  im.chat({ id: 'room', type: 'group', groupname: '讨论组' })
  im.setGroupMute('room', true)
  await nextTick()
  expect(target.querySelector<HTMLTextAreaElement>('textarea')?.disabled).toBe(true)
  im.setGroupMute('room', true, 'me')
  im.setGroupMute('room', false)
  await nextTick()
  expect(target.querySelector<HTMLTextAreaElement>('textarea')?.disabled).toBe(true)
  im.setGroupMute('room', false, 'me')
  await nextTick()
  expect(target.querySelector<HTMLTextAreaElement>('textarea')?.disabled).toBe(false)
  im.setGroupMute('room', true)
  im.chat({ id: 'alice', type: 'friend', username: 'Alice' })
  await nextTick()
  expect(target.querySelector<HTMLTextAreaElement>('textarea')?.disabled).toBe(false)
  expect(onSendMessage).not.toHaveBeenCalled()
  im.destroy()
})

it('blocks text and an attachment that finishes uploading after a mute update', async () => {
  let finishUpload!: (url: string) => void
  const uploadAttachment = vi.fn(() => new Promise<string>(resolve => { finishUpload = resolve }))
  const wrapper = mount(ImWidget, { props: { init: { ...init, group: [{ ...init.group![0], ownerId: 'alice' }] }, uploadAttachment } })
  const api = wrapper.vm as unknown as ImWidgetApi
  api.chat({ id: 'room', type: 'group', groupname: '讨论组' })
  await nextTick()
  const input = wrapper.get('input[type="file"][accept="image/*"]')
  Object.defineProperty(input.element, 'files', { value: [new File(['image'], 'photo.png', { type: 'image/png' })] })
  await input.trigger('change')
  await wrapper.get('[aria-label="输入消息"]').setValue('发送之前禁言')
  api.setGroupMute('room', true, 'me')
  await nextTick()
  await wrapper.get('[aria-label="输入消息"]').trigger('keydown', { key: 'Enter' })
  finishUpload('https://example.test/photo.png')
  await flushPromises()
  expect(wrapper.emitted('sendMessage')).toBeUndefined()
  expect(wrapper.findAll('.gim-message')).toHaveLength(0)
  wrapper.unmount()
})
